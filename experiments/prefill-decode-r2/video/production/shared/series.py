"""Shared code of the series: concept colours (series-bible.md) and the board built from lesson_states.json.

Board states are generated by lesson/checkpoints.js (`node build.mjs`); scenes never retype business rules.
Columns are positions 1-5, rows are layer 1 (lower) and layer 2 (upper); input chips below, picked chips above.
"""

import json
from pathlib import Path

from explainer_studio.scene_kit import *

PROMPT_COLOR = "#5B8DEF"
ANSWER_COLOR = "#E0B04B"
KV_COLOR = "#3FB5A3"
ACTIVE_COLOR = HIGHLIGHT_COLOR
BLOCKED_COLOR = "#E06C5F"
STRUCTURE_COLOR = GREY_B

STATES = json.loads((Path(__file__).parent / "lesson_states.json").read_text())

COLUMN_XS = [-4.2, -2.2, -0.2, 1.8, 3.8]
ROW_YS = [-0.45, 0.75]
INPUT_Y = -1.85
PICK_Y = 2.25
CELL_W, CELL_H = 1.5, 0.8
CHIP_SIZE = 34
LABEL_SIZE = 28


def get_state(checkpoint: str, cache: bool = True) -> dict:
    return STATES["states"][checkpoint]["cache_on" if cache else "cache_off"]


def cell_center(layer: int, column: int) -> np.ndarray:
    return np.array([COLUMN_XS[column], ROW_YS[layer], 0.0])


def get_chip(token: str, role: str = "prompt") -> Parts:
    """A token chip. Parts: .box, .label."""
    color = PROMPT_COLOR if role == "prompt" else ANSWER_COLOR
    label = Text(token, font_size=CHIP_SIZE).set_color(WHITE)
    box = RoundedRectangle(width=max(label.get_width() + 0.45, 1.25), height=0.72, corner_radius=0.14)
    box.set_fill(color, 0.25).set_stroke(color, 3)
    label.move_to(box)
    chip = Parts(box, label)
    chip.box, chip.label = box, label
    return chip


def get_cell(kind: str, layer: int, column: int, show_kv: bool = True) -> VMobject:
    """One cell. kinds: empty, processed, kv, new, reused, rebuilt, cleared (cache off, grey dashed K V)."""
    rect = RoundedRectangle(width=CELL_W, height=CELL_H, corner_radius=0.1).move_to(cell_center(layer, column))
    if kind == "empty":
        return DashedVMobject(rect, num_dashes=22).set_stroke(GREY_C, 2)
    if not show_kv:
        stroke = ACTIVE_COLOR if kind == "new" else WHITE
        return rect.set_stroke(stroke, 2.5).set_fill(WHITE, 0.12)
    if kind == "cleared":
        tag = Text("K V", font_size=26).set_color(GREY_C).move_to(rect)
        return VGroup(DashedVMobject(rect, num_dashes=22).set_stroke(GREY_C, 2), tag)
    stroke = {"kv": KV_COLOR, "new": ACTIVE_COLOR, "reused": KV_COLOR, "rebuilt": BLOCKED_COLOR, "processed": WHITE}[kind]
    rect.set_stroke(stroke, 3 if kind != "kv" else 2).set_fill(KV_COLOR, 0.35)
    tag = Text("K V", font_size=26).set_color(WHITE).move_to(rect)
    return VGroup(rect, tag)


class Board:
    """Live board objects by position. `cell_to(layer, column, kind)` returns an animation and records the new cell."""

    def __init__(self, state: dict, show_kv: bool = True, columns: int | None = None) -> None:
        self.show_kv = show_kv
        count = columns if columns is not None else len(state["columns"])
        self.cells: dict[tuple[int, int], VMobject] = {}
        self.chips: dict[int, Parts] = {}
        self.numbers = VGroup()
        self.layer_labels = VGroup()
        for layer, y in enumerate(ROW_YS):
            label = Text(f"layer {layer + 1}", font_size=LABEL_SIZE).set_color(GREY_B)
            label.move_to([COLUMN_XS[0] - CELL_W / 2 - 0.25, y, 0], aligned_edge=RIGHT)
            self.layer_labels.add(label)
        for c in range(count):
            column = state["columns"][c] if c < len(state["columns"]) else None
            for layer in range(len(ROW_YS)):
                kind = state["cells"][layer][c] if column else "empty"
                self.cells[(layer, c)] = get_cell(kind, layer, c, show_kv)
            if column:
                chip = get_chip(column["token"], column["role"])
                chip.move_to([COLUMN_XS[c], PICK_Y if column["slot"] == "picked" else INPUT_Y, 0])
                self.chips[c] = chip
            number = Text(str(c + 1), font_size=LABEL_SIZE).set_color(GREY_B)
            self.numbers.add(number.move_to([COLUMN_XS[c], INPUT_Y - 0.7, 0]))

    def column(self, c: int) -> VGroup:
        return VGroup(*(self.cells[(l, c)] for l in range(len(ROW_YS)) if (l, c) in self.cells))

    def row(self, layer: int, columns: range) -> VGroup:
        return VGroup(*(self.cells[(layer, c)] for c in columns))

    def grid(self) -> VGroup:
        return VGroup(*self.cells.values())

    def chip_group(self) -> VGroup:
        return VGroup(*self.chips.values())

    def everything(self) -> VGroup:
        return VGroup(self.grid(), self.chip_group(), self.numbers, self.layer_labels)

    def cell_to(self, layer: int, column: int, kind: str) -> Animation:
        old = self.cells[(layer, column)]
        new = get_cell(kind, layer, column, self.show_kv)
        self.cells[(layer, column)] = new
        return FadeTransform(old, new)


def get_input_slot(column: int) -> VMobject:
    box = RoundedRectangle(width=1.25, height=0.72, corner_radius=0.14).move_to([COLUMN_XS[column], INPUT_Y, 0])
    return DashedVMobject(box, num_dashes=18).set_stroke(GREY_C, 2)


def get_reads(state: dict) -> VGroup:
    """A compact read bus below the layer: current position uses allowed past and its own K/V."""
    arrows = state["arrows"]; layer=arrows["layer"]; source=arrows["from"]
    bottom=ROW_YS[layer]-CELL_H/2; bus_y=bottom-0.30
    xs=[COLUMN_XS[c] for c in arrows["reads"]]
    group=VGroup(Line([min(xs),bus_y,0],[COLUMN_XS[source],bus_y,0]).set_stroke(STRUCTURE_COLOR,2))
    for target in arrows["reads"]:
        xx=COLUMN_XS[target]
        group.add(Arrow([xx,bus_y,0],[xx,bottom-0.02,0],buff=0,thickness=2,max_tip_length_to_length_ratio=0.3).set_color(STRUCTURE_COLOR))
    return group


def get_blocked(state: dict) -> VGroup:
    """The red dashed 'no looking ahead' arrow, above its row, with its label."""
    b = state["arrows"]["blocked"]
    top = CELL_H / 2 + 0.05
    start = cell_center(b["layer"], b["from"]) + top * UP
    end = cell_center(b["layer"], b["to"]) + top * UP + 0.2 * LEFT
    arrow = get_curved_arrow(start, end, angle=-PI / 2.5, color=BLOCKED_COLOR, stroke_width=3, tip_size=0.16)
    dashed = DashedVMobject(arrow.arc, num_dashes=10).set_stroke(BLOCKED_COLOR, 3)
    label = Text("× no looking ahead", font_size=LABEL_SIZE).set_color(BLOCKED_COLOR)
    label.next_to(VGroup(dashed, arrow.tip), UP, buff=0.15)
    return VGroup(dashed, arrow.tip, label)


def get_score_panel(state: dict) -> Parts:
    """Toy scores (top 3) as bars, top-left of the board. Parts: .rows (by token), .caption."""
    scores = state["scores"]["list"]
    top = max(s["score"] for s in scores)
    rows = VGroup()
    by_token = {}
    for s in scores:
        name = Text(s["token"], font_size=LABEL_SIZE).set_color(WHITE)
        bar = Rectangle(width=2.0 * max(s["score"], 0.08) / top, height=0.26).set_fill(GREY_B, 0.9).set_stroke(width=0)
        value = Text(f"{s['score']:.2f}", font_size=LABEL_SIZE).set_color(GREY_A)
        name.set_width(name.get_width()).move_to(ORIGIN, aligned_edge=RIGHT)
        bar.next_to(name, RIGHT, buff=0.25)
        value.next_to(bar, RIGHT, buff=0.2)
        row = VGroup(name, bar, value)
        row.bar = bar
        by_token[s["token"]] = row
        rows.add(row)
    rows.arrange(DOWN, buff=0.18, aligned_edge=LEFT)
    caption = Text("toy scores", font_size=24).set_color(GREY_B).next_to(rows, UP, buff=0.15, aligned_edge=LEFT)
    panel = Parts(caption, rows)
    panel.rows, panel.caption, panel.by_token = rows, caption, by_token
    panel.move_to([-3.6, 2.35, 0])
    return panel


def get_top_line(text: str, color: str = WHITE) -> Text:
    return Text(text, font_size=36).set_color(color).to_edge(UP, buff=0.45)
