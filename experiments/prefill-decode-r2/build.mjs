// Build: node build.mjs
// 1. video/production/episodes/ep01/script.yaml   (generated from lesson/story.js; edit the story, not the YAML)
// 2. video/production/shared/lesson_states.json   (checkpoint states for the ManimGL scenes)
// 3. interactive/index.html                       (one self-contained file: inline CSS, JS and SVG)
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SCENES } from "./lesson/story.js";
import { exportStates } from "./lesson/checkpoints.js";

const root = dirname(fileURLToPath(import.meta.url));
const at = (...p) => join(root, ...p);
const write = (path, text) => { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, text); };

// 1. script.yaml — JSON strings are valid YAML double-quoted scalars.
const s = JSON.stringify;
let yaml = "# GENERATED by build.mjs from lesson/story.js. Edit the story module, then run `node build.mjs`.\nscenes:\n";
for (const scene of SCENES) {
  yaml += `  - id: ${scene.id}\n    purpose: ${s(scene.purpose)}\n    beats:\n`;
  for (const beat of scene.beats) {
    yaml += `      - id: ${beat.id}\n        narration_text: ${s(beat.narration)}\n        visual: ${s(beat.visual)}\n`;
    if (beat.pause !== undefined) yaml += `        pause_duration_seconds: ${beat.pause}\n`;
    if (beat.spoken) yaml += `        spoken_text_override: ${s(beat.spoken)}\n`;
  }
}
write(at("video/production/episodes/ep01/script.yaml"), yaml);

// 2. checkpoint states for Python
write(at("video/production/shared/lesson_states.json"), JSON.stringify(exportStates(), null, 1) + "\n");

// 3. interactive — inline the pure modules (exports/imports stripped) ahead of the app.
const strip = (src) => src.replace(/^import .*$/gm, "").replace(/^export (const|function|let)/gm, "$1");
const modules = ["lesson/mechanism.js", "lesson/checkpoints.js", "lesson/story.js"].map((f) => `// ${f}\n${strip(readFileSync(at(f), "utf8"))}`);
const script = `(() => {\n"use strict";\n${modules.join("\n")}\n// interactive/src/app.js\n${readFileSync(at("interactive/src/app.js"), "utf8")}\n})();`;
if (/<\/script/i.test(script)) throw new Error("script contains </script>");
const html = readFileSync(at("interactive/src/template.html"), "utf8")
  .replace("{{STYLE}}", () => readFileSync(at("interactive/src/styles.css"), "utf8"))
  .replace("{{SCRIPT}}", () => script);
write(at("interactive/index.html"), html);
console.log(`built: script.yaml (${SCENES.length} scenes), lesson_states.json, interactive/index.html (${(html.length / 1024).toFixed(1)} KB)`);

// Preserve genuine reads as small source records. Seed Studio only for a fresh checkout;
// never overwrite later local reviewer rounds during an ordinary build.
const reviewDirectory=at("review/audience");
const studioReview=at("video/production/episodes/ep01/audience-reviews/script.yaml");
if(existsSync(reviewDirectory)&&!existsSync(studioReview)) {
  const rounds=readdirSync(reviewDirectory).filter(n=>/^round-\d+\.json$/.test(n)).sort().map(n=>JSON.parse(readFileSync(join(reviewDirectory,n),"utf8")));
  write(studioReview,JSON.stringify({rounds},null,2)+"\n"); // JSON is valid YAML.
}
